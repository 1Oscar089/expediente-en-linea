const ordenar = (lista: string[]) => [...lista].sort((a, b) => a.localeCompare(b, 'es'))

/* Departamentos en orden alfabético */
export const DEPARTAMENTOS_SV: string[] = ordenar(Object.keys(DEPARTAMENTOS))

/* Distritos del departamento elegido (alfabético) */
export function distritosDe(departamento: string): string[] {
  return ordenar(DEPARTAMENTOS[departamento] ?? [])
}

/* Cantones del distrito (SOLO Chalatenango). Devuelve null cuando el
   distrito no está en el catálogo (cualquier departamento que no sea
   Chalatenango) y [] cuando no tiene cantones. */
export function cantonesDe(distrito: string): string[] | null {
  const lista = CANTONES[distrito]
  return lista ? ordenar(lista) : null
}
